#!/usr/bin/env node
/**
 * Build the only directory Vercel is allowed to publish.
 *
 * The repository root contains migrations, tests, setup SQL and visual-review
 * artifacts that must never become public files. This builder copies an
 * explicit allowlist, fingerprints every executable/style asset, rewrites page
 * references, and generates a content-versioned service worker.
 */
import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public');
const BUILD_ASSETS = join(OUT, 'assets', 'build');

const pages = [
  'index.html',
  'account.html',
  'admin.html',
  'admin-login.html',
  'admin-drop.html',
  'drop.html',
  'order-confirmed.html',
  'swap.html',
  'used.html',
  'admin-control.html',
  'wholesale.html',
  'partner.html',
];
const publicFiles = [
  'favicon.png', 'favicon.svg', 'logo.png', 'logo.svg',
  'manifest.json', 'robots.txt', 'sitemap.xml',
];
const assetSources = new Map([
  ['tailwind.min.css', 'tailwind.min.css'],
  ['mobile-fixes.css', 'mobile-fixes.css'],
  ['assets/css/community.css', 'assets/css/community.css'],
  ['assets/css/valmontai.css', 'assets/css/valmontai.css'],
  ['assets/js/account.js', 'assets/js/account.js'],
  ['assets/js/admin.js', 'assets/js/admin.js'],
  ['assets/js/admin-login.js', 'assets/js/admin-login.js'],
  ['assets/js/admin-drop.js', 'assets/js/admin-drop.js'],
  ['assets/js/analytics.js', 'assets/js/analytics.js'],
  ['assets/js/catalog.min.js', 'assets/js/catalog.min.js'],
  ['assets/js/drop.js', 'assets/js/drop.js'],
  ['assets/js/order-confirmed.js', 'assets/js/order-confirmed.js'],
  ['assets/js/page-init.js', 'assets/js/page-init.js'],
  ['assets/js/password-reset.js', 'assets/js/password-reset.js'],
  ['assets/js/storefront.js', 'assets/js/storefront.js'],
  ['assets/js/security.js', 'assets/js/security.js'],
  ['assets/js/supabase-client.js', 'assets/js/supabase-client.js'],
  ['assets/js/db-adapter.js', 'assets/js/db-adapter.js'],
  ['assets/js/swap-page.js', 'assets/js/swap-page.js'],
  ['assets/js/used-page.js', 'assets/js/used-page.js'],
  ['assets/js/valmontai.js', 'assets/js/valmontai.js'],
  ['assets/js/wholesale-page.js', 'assets/js/wholesale-page.js'],
  ['assets/js/partner-page.js', 'assets/js/partner-page.js'],
  ['assets/js/admin-control-page.js', 'assets/js/admin-control-page.js'],
  ['assets/js/vendor/supabase-2.112.1.min.js', 'assets/js/vendor/supabase-2.112.1.min.js'],
  // Production uses the generated/minified storefront, never app.js directly.
  ['app.js', 'shop.min.js'],
]);

const digest = (input, length = 16) => createHash('sha256').update(input).digest('hex').slice(0, length);
const posix = (value) => value.replaceAll('\\', '/');

await rm(OUT, { recursive: true, force: true });
await mkdir(BUILD_ASSETS, { recursive: true });

const manifest = {};
const precache = new Set(['/']);
for (const [pageRef, source] of assetSources) {
  const bytes = await readFile(join(ROOT, source));
  const extension = source.endsWith('.css') ? 'css' : 'js';
  const stem = pageRef.split('/').pop().replace(/\.(?:min\.)?(?:css|js)$/i, '');
  const outputRef = `/assets/build/${stem}.${digest(bytes)}.${extension}`;
  await writeFile(join(OUT, outputRef), bytes);
  manifest[pageRef] = outputRef;
  precache.add(outputRef);
}

for (const page of pages) {
  let html = await readFile(join(ROOT, page), 'utf8');
  for (const [sourceRef, outputRef] of Object.entries(manifest)) {
    html = html.replaceAll(`src="${sourceRef}"`, `src="${outputRef}"`);
    html = html.replaceAll(`href="${sourceRef}"`, `href="${outputRef}"`);
  }
  await writeFile(join(OUT, page), html);
  if (['index.html', 'drop.html'].includes(page)) precache.add(`/${page}`);
}

for (const file of publicFiles) {
  await cp(join(ROOT, file), join(OUT, file));
}
await cp(join(ROOT, 'uploads'), join(OUT, 'uploads'), { recursive: true });
await cp(join(ROOT, 'assets', 'images'), join(OUT, 'assets', 'images'), { recursive: true });

for (const file of ['manifest.json', 'logo.svg', 'logo.png', 'favicon.svg', 'favicon.png']) {
  precache.add(`/${file}`);
}

const assetManifest = JSON.stringify(
  Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b))),
  null,
  2,
) + '\n';
await writeFile(join(OUT, 'asset-manifest.json'), assetManifest);

const cacheVersion = digest([...precache].sort().join('\n') + assetManifest);
const serviceWorker = `/* Generated by scripts/build-production.mjs. Do not edit the artifact. */
const CACHE_NAME = 'valmont-${cacheVersion}';
const PRECACHE = ${JSON.stringify([...precache].sort(), null, 2)};
const PUBLIC_NAVIGATIONS = new Set(['/', '/index.html', '/drop.html']);

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await Promise.allSettled(PRECACHE.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok && PUBLIC_NAVIGATIONS.has(url.pathname)) {
          const cache = await caches.open(CACHE_NAME);
          await cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        const cached = await caches.match(request);
        if (cached) return cached;
        if (PUBLIC_NAVIGATIONS.has(url.pathname)) {
          const home = await caches.match('/index.html') || await caches.match('/');
          if (home) return home;
        }
        return new Response('This page is unavailable while offline.', {
          status: 503,
          headers: { 'Content-Type': 'text/plain; charset=utf-8' },
        });
      }
    })());
    return;
  }

  if (url.pathname.startsWith('/assets/build/')) {
    event.respondWith((async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        await cache.put(request, response.clone());
      }
      return response;
    })());
    return;
  }

  // Non-fingerprinted media must be revalidated. The HTTP cache handles the
  // normal case; a previously precached response is only an offline fallback.
  event.respondWith(fetch(request).catch(async () => {
    const cached = await caches.match(request);
    return cached || new Response('', { status: 504 });
  }));
});
`;
await writeFile(join(OUT, 'sw.js'), serviceWorker);

// Artifact assertions: fail closed if an unsafe HTML construct or dangling
// local asset reference reaches the publish directory.
for (const page of pages) {
  const html = await readFile(join(OUT, page), 'utf8');
  const dom = new JSDOM(html);
  const { document } = dom.window;
  for (const element of document.querySelectorAll('*')) {
    for (const attribute of element.getAttributeNames()) {
      // Every page in this build is CSP'd with script-src-attr 'none' (vercel.json),
      // so an inline handler here would be a silent dead button in production.
      if (/^on/i.test(attribute)) {
        throw new Error(`${page}: inline event attribute ${attribute}`);
      }
    }
  }
  for (const script of document.querySelectorAll('script:not([src])')) {
    if (script.type !== 'application/ld+json') {
      // Blocked by script-src 'self'; the only tolerated inline script is the
      // JSON-LD structured data above.
      throw new Error(`${page}: executable inline script`);
    }
  }
  for (const element of document.querySelectorAll('script[src],link[href]')) {
    const ref = element.getAttribute(element.hasAttribute('src') ? 'src' : 'href');
    if (!ref || /^(?:https?:|mailto:|#|data:)/.test(ref)) continue;
    const pathname = ref.split(/[?#]/)[0].replace(/^\//, '');
    if (!pathname || !/\.(?:js|css|png|svg|json|ico|webp|woff2)$/i.test(pathname)) continue;
    try { await readFile(join(OUT, pathname)); }
    catch { throw new Error(`${page}: missing local asset ${ref}`); }
  }
  if (/\b(?:app|shop)\.min?\.js\b/.test(html)) {
    throw new Error(`${page}: unhashed storefront script reference`);
  }
  if (/src="assets\/js\//.test(html) || /href="(?:tailwind\.min|mobile-fixes|assets\/css\/)/.test(html)) {
    throw new Error(`${page}: unhashed executable/style asset reference`);
  }
}

const forbidden = ['preview-content.html', 'preview-mobile.html', 'SETUP_ALL_IN_ONE.txt', 'valmont_setup.sql', 'part1_tables.sql', 'part2_setup.sql'];
for (const file of forbidden) {
  try {
    await readFile(join(OUT, file));
    throw new Error(`forbidden production artifact: ${file}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

console.log(`Built allowlisted production artifact: ${relative(ROOT, OUT)}/`);
console.log(`Fingerprint version: ${cacheVersion}`);
console.log(`${pages.length} pages, ${Object.keys(manifest).length} fingerprinted assets`);
